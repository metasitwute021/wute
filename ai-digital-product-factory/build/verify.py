#!/usr/bin/env python3
"""Post-build checks: JavaScript syntax of every Code node + a real PDF smoke test.

    python3 build/verify.py

Needs Node.js on the PATH. Nothing here talks to OpenAI, Etsy or Google.
"""

from __future__ import annotations

import glob
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from js_pdf import PDF_LIB_JS  # noqa: E402
from wf03 import PLACEHOLDER_JPEG  # noqa: E402

WORKFLOW_DIR = os.path.join(ROOT, "workflows")


def check_code_nodes(tmp: str) -> list[str]:
    """Every Code node body must parse. n8n only tells you at runtime."""
    problems = []
    checked = 0
    for filename in sorted(os.listdir(WORKFLOW_DIR)):
        if not filename.endswith(".json"):
            continue
        with open(os.path.join(WORKFLOW_DIR, filename), encoding="utf-8") as fh:
            document = json.load(fh)
        for node in document["nodes"]:
            source = node["parameters"].get("jsCode")
            if not source:
                continue
            checked += 1
            # n8n runs the body inside an async function, so top-level return
            # and await are legal. Wrap it the same way before parsing.
            path = os.path.join(tmp, "check.js")
            with open(path, "w", encoding="utf-8") as fh:
                fh.write("async function __n8nCodeNode() {\n" + source + "\n}\n")
            result = subprocess.run(
                ["node", "--check", path], capture_output=True, text=True
            )
            if result.returncode != 0:
                head = result.stderr.strip().splitlines()
                problems.append(f"{filename} :: {node['name']}\n    " + "\n    ".join(head[:6]))
    print(f"[ok] parsed {checked} Code node bodies")
    return problems


def check_pdf(tmp: str) -> list[str]:
    """Build a real PDF with the same writer the workflow uses."""
    harness = (
        PDF_LIB_JS
        + "\n\n"
        + f"const JPEG = '{PLACEHOLDER_JPEG}';\n"
        + """
const lorem = Array.from({ length: 120 }, (_, i) =>
  `Line ${i + 1}: this sentence exists to force the writer to wrap text and to ` +
  'spill the content across more than one physical page of the document.');

const result = buildPdf({
  width: 595.28,
  height: 841.89,
  info: { title: 'Smoke Test Product', subject: 'verification', keywords: 'a, b' },
  pages: [
    { type: 'image', jpeg_base64: JPEG, full_bleed: true },
    { type: 'text', cover: true, title: 'Smoke Test Product',
      subtitle: 'Generated by build/verify.py', lines: ['Intro line', '', '- one', '- two'],
      footer: 'smoke test' },
    { type: 'text', title: 'Long chapter', lines: lorem, footer: 'smoke test | page 2' },
    { type: 'image', jpeg_base64: JPEG, caption: 'A caption', footer: 'smoke test | page 3' },
  ],
});

require('fs').writeFileSync(process.argv[2], result.buffer);
console.log(JSON.stringify({ pages: result.page_count, bytes: result.buffer.length }));
"""
    )
    script = os.path.join(tmp, "pdf_harness.js")
    output = os.path.join(tmp, "smoke.pdf")
    with open(script, "w", encoding="utf-8") as fh:
        fh.write(harness)

    result = subprocess.run(
        ["node", script, output], capture_output=True, text=True
    )
    if result.returncode != 0:
        return ["PDF harness crashed:\n" + result.stderr.strip()]

    stats = json.loads(result.stdout.strip().splitlines()[-1])
    with open(output, "rb") as fh:
        data = fh.read()

    problems = []
    if not data.startswith(b"%PDF-1.4"):
        problems.append("PDF header missing")
    if not data.rstrip().endswith(b"%%EOF"):
        problems.append("PDF trailer missing")
    if b"/DCTDecode" not in data:
        problems.append("JPEG image was not embedded")
    if stats["pages"] < 5:
        problems.append(f"expected the long chapter to paginate, got {stats['pages']} pages")

    # Walk the cross-reference table: every offset must land exactly on the
    # object it claims. A wrong offset is the classic hand-rolled-PDF bug and
    # readers fail on it in ways that are painful to debug from n8n.
    tail = data[-2048:].decode("latin1")
    startxref = int(tail.rsplit("startxref", 1)[1].strip().split()[0])
    if data[startxref:startxref + 4] != b"xref":
        problems.append("startxref does not point at the xref table")
    else:
        xref = data[startxref:].decode("latin1")
        declared = int(re.match(r"xref\s+0\s+(\d+)\s+", xref).group(1))
        entries = re.findall(r"(\d{10}) (\d{5}) ([nf])", xref[: declared * 20 + 64])
        if len(entries) != declared:
            problems.append(f"xref declares {declared} objects but lists {len(entries)}")
        for index, (offset, _gen, kind) in enumerate(entries):
            if kind == "f":
                continue
            if not re.match(rf"^{index} 0 obj", data[int(offset):int(offset) + 24].decode("latin1")):
                problems.append(f"xref offset for object {index} does not point at it")

    page_objects = len(re.findall(rb"/Type /Page[^s]", data))
    declared_pages = int(re.search(rb"/Type /Pages /Count (\d+)", data).group(1))
    if len({page_objects, declared_pages, stats["pages"]}) != 1:
        problems.append(
            f"page count mismatch: {page_objects} objects, /Count {declared_pages}, "
            f"builder reported {stats['pages']}"
        )

    print(f"[ok] PDF smoke test: {stats['pages']} pages, {stats['bytes']} bytes, "
          f"xref at {startxref}, {len(re.findall(rb'/DCTDecode', data))} embedded JPEGs")
    return problems


def check_sql() -> list[str]:
    """Parse every PostgreSQL statement with the real PostgreSQL grammar.

    ``pglast`` wraps libpg_query - the parser PostgreSQL itself uses - so this
    catches reserved words, typos and malformed CTEs without a live server.
    Skipped (with a warning) when pglast is not installed.
    """
    try:
        import pglast
    except ImportError:
        print("[skip] SQL check - pip install pglast to enable it")
        return []

    problems = []
    checked = 0

    schema = os.path.join(ROOT, "db", "schema.postgres.sql")
    if os.path.exists(schema):
        with open(schema, encoding="utf-8") as fh:
            try:
                pglast.parse_sql(fh.read())
                checked += 1
            except Exception as exc:  # noqa: BLE001 - message is the useful part
                problems.append(f"db/schema.postgres.sql\n    {exc}")

    for filename in sorted(os.listdir(WORKFLOW_DIR)):
        if not filename.endswith(".json"):
            continue
        with open(os.path.join(WORKFLOW_DIR, filename), encoding="utf-8") as fh:
            document = json.load(fh)
        for node in document["nodes"]:
            if node["type"] != "n8n-nodes-base.postgres":
                continue
            query = node["parameters"].get("query", "")
            # A query built by an expression is only known at runtime.
            if not query or query.startswith("="):
                continue
            checked += 1
            try:
                pglast.parse_sql(query)
            except Exception as exc:  # noqa: BLE001
                problems.append(f"{filename} :: {node['name']}\n    {exc}")

    # The statements 06 injects into its Code node never appear in a node param.
    import wf06  # noqa: PLC0415 - imported here so a missing pglast skips cleanly

    for name in ("SQL_POSTGRES", "SQL_QA_RESULT", "SQL_PRODUCT_VERSION"):
        checked += 1
        try:
            pglast.parse_sql(getattr(wf06, name))
        except Exception as exc:  # noqa: BLE001
            problems.append(f"wf06.{name}\n    {exc}")

    print(f"[ok] parsed {checked} PostgreSQL statements")
    return problems


def check_input_fields() -> list[str]:
    """Catch a Code node reading fields its predecessor does not emit.

    Build Idea Prompt read ctx.research off $input while its feeder emitted a
    QA verdict, so the agent was handed the literal string "undefined" and no
    node failed - the run only went wrong three stages later. A node addressed
    by name ($('X').first().json) is unaffected; this only checks $input.
    """
    problems: list[str] = []
    ctx_from_input = re.compile(r"const ctx = \$input\b")
    field_use = re.compile(r"\bctx\.(\w+)")

    for path in sorted(glob.glob(os.path.join(ROOT, "workflows", "*.json"))):
        with open(path, encoding="utf-8") as fh:
            document = json.load(fh)
        nodes = {n["name"]: n for n in document["nodes"]}
        feeders: dict[str, list[str]] = {}
        for source, outputs in document["connections"].items():
            for branch in outputs.get("main", []):
                for link in branch:
                    feeders.setdefault(link["node"], []).append(source)

        for name, node in nodes.items():
            code = node["parameters"].get("jsCode")
            if not code or not ctx_from_input.search(code):
                continue
            fields = sorted(set(field_use.findall(code)))
            for feeder in feeders.get(name, []):
                feeder_code = nodes[feeder]["parameters"].get("jsCode")
                if not feeder_code:
                    continue                      # not a Code node: shape unknown
                tail = feeder_code[feeder_code.rfind("return "):]
                if re.search(r"\.\.\.\s*\w+(\.json)?\b", tail):
                    continue                      # spreads its input: passes through
                missing = [f for f in fields if not re.search(rf"\b{f}\b", tail)]
                if missing:
                    problems.append(
                        f"{os.path.basename(path)}: '{name}' reads $input."
                        f"{{{', '.join(missing)}}} but '{feeder}' does not emit "
                        f"{'it' if len(missing) == 1 else 'them'}")
    print(f"[{'ok' if not problems else 'FAILED'}] checked $input field reads "
          f"against their feeders")
    return problems


def main() -> int:
    if subprocess.run(["node", "-v"], capture_output=True).returncode != 0:
        print("node is required for verify.py")
        return 1

    problems: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        problems += check_code_nodes(tmp)
        problems += check_sql()
        problems += check_pdf(tmp)
    problems += check_input_fields()

    if problems:
        print(f"\n{len(problems)} problem(s):")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print("\nall checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
